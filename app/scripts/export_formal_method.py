"""Export the author-owned definition/compiler to an explicitly named consumer.

No runtime compatibility adapter is generated. Provider source and generated
schema are pinned together so a consumer cannot silently interpret a new shape.
"""

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

from app.domain.knowbots.formal_method_admission import (
    FormalMethodDraft,
    FormalMethodValidationResult,
    FrozenFormalMethod,
)
from app.domain.knowbots.formal_method_execution import (
    BranchDelivery,
    ExecuteFormalMethod,
    FormalExecutionInput,
    FormalMethodExecutionRequest,
    FormalMethodExecutionResult,
    FormalTestSuite,
    PrepareBranchReview,
    ReceiveBranch,
)
from app.domain.knowbots.schema import FORMAL_METHOD, render

HEADER = "# Generated by KnowLab scripts/export_formal_method.py; do not edit.\n"
FILES = {
    "formal_method.py": "formal_method_generated.py",
    "formal_method_compiler.py": "formal_method_compiler_generated.py",
    "formal_method_plan.py": "formal_method_plan_generated.py",
    "formal_method_admission.py": "formal_method_admission_generated.py",
    "formal_method_execution.py": "formal_method_execution_generated.py",
}
BACKEND_FILES = {**FILES, "selection.py": "incubation_selection.py"}
WEB_MODELS = {
    "draft": FormalMethodDraft,
    "execution-command": ExecuteFormalMethod,
    "execution-input": FormalExecutionInput,
    "execution-request": FormalMethodExecutionRequest,
    "execution-result": FormalMethodExecutionResult,
    "branch-review-request": PrepareBranchReview,
    "partial-delivery-request": ReceiveBranch,
    "partial-delivery-result": BranchDelivery,
    "validation-result": FormalMethodValidationResult,
    "registration-request": FrozenFormalMethod,
    "suite": FormalTestSuite,
}


def exported(source: str) -> str:
    source = source.replace(
        "app.domain.knowbots.test_run", "app.domain.workbench.test_runs"
    ).replace(
        "app.domain.knowbots.managed_capabilities_generated",
        "app.domain.workbench.method_capabilities",
    )
    for name in sorted(BACKEND_FILES, key=len, reverse=True):
        source = source.replace(
            "app.domain.knowbots." + Path(name).stem,
            "app.domain.workbench." + Path(BACKEND_FILES[name]).stem,
        )
    # Rewriting module names changes both import ordering and line lengths.
    # Generate the consumer's formatted source instead of hand-editing it later.
    config = Path(__file__).resolve().parents[1] / "pyproject.toml"
    source = HEADER + source
    for args in (
        [
            "check",
            "--fix",
            "--select",
            "I",
            "--config",
            "lint.isort.known-first-party = ['app']",
        ],
        ["format"],
    ):
        source = subprocess.run(
            [
                sys.executable,
                "-m",
                "ruff",
                *args,
                "--config",
                str(config),
                "--stdin-filename",
                "formal_method_generated.py",
                "-",
            ],
            input=source,
            text=True,
            capture_output=True,
            check=True,
        ).stdout
    return source


def generate(consumer: Path) -> dict[Path, str]:
    provider = Path(__file__).resolve().parents[1] / "app/domain/knowbots"
    sources = {name: (provider / name).read_text() for name in BACKEND_FILES}
    outputs = {
        consumer / "app/domain/workbench" / BACKEND_FILES[name]: exported(content)
        for name, content in sources.items()
    }
    schema = render("definition.schema.json", FORMAL_METHOD)
    outputs[consumer / "contracts/formal-method-v1.json"] = schema
    validation_schemas = {
        name: render(name + ".schema.json", FORMAL_METHOD)
        for name in (
            "validation-request",
            "validation-result",
            "registration-request",
            "registration-result",
            "execution-request",
            "execution-result",
            "execution-decision",
            "partial-delivery-request",
            "partial-delivery-result",
            "branch-review-request",
        )
    }
    for name, content in validation_schemas.items():
        outputs[consumer / f"contracts/formal-method-{name}-v1.json"] = content
    lock = {
        "provider": "knowlab",
        "contract": "knowlab/formal-method/v1",
        "source_sha256": {
            name: hashlib.sha256(value.encode()).hexdigest()
            for name, value in sources.items()
        },
        "generated_sha256": {
            path.name: hashlib.sha256(value.encode()).hexdigest()
            for path, value in outputs.items()
            if path.suffix == ".py"
        },
        "schema_sha256": hashlib.sha256(schema.encode()).hexdigest(),
        "validation_schema_sha256": {
            name: hashlib.sha256(content.encode()).hexdigest()
            for name, content in validation_schemas.items()
        },
    }
    outputs[consumer / "contracts/formal-method-lock.json"] = (
        json.dumps(lock, indent=2) + "\n"
    )
    return outputs


def generate_web(consumer: Path) -> dict[Path, str]:
    """Only data files in one browser bundle, never Python source in a web app."""
    base = Path(__file__).resolve().parents[1]
    target = consumer / "contracts/formal-method-provider"
    texts = {
        name + ".schema.json": json.dumps(
            {
                "$schema": "https://json-schema.org/draft/2020-12/schema",
                "$id": f"https://contracts.sunmoonai.com/knowlab/formal-method/v1/{name}.schema.json",
                **model.model_json_schema(),
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n"
        for name, model in WEB_MODELS.items()
    }
    texts["samples.json"] = (
        base / "contracts/formal-method-web.samples.json"
    ).read_text()
    lock = {
        "provider": "knowlab",
        "contract": "knowlab/formal-method/v1",
        "source_sha256": {
            name: hashlib.sha256(
                (base / "app/domain/knowbots" / name).read_bytes()
            ).hexdigest()
            for name in FILES
        },
        "files_sha256": {
            name: hashlib.sha256(value.encode()).hexdigest()
            for name, value in sorted(texts.items())
        },
    }
    texts["lock.json"] = json.dumps(lock, indent=2) + "\n"
    return {target / name: value for name, value in texts.items()}


def main():
    parser = argparse.ArgumentParser()
    target = parser.add_mutually_exclusive_group(required=True)
    target.add_argument("--consumer", type=Path)
    target.add_argument("--web-consumer", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = (
        generate_web(args.web_consumer.resolve())
        if args.web_consumer
        else generate(args.consumer.resolve())
    )
    if args.check:
        changed = [
            str(path)
            for path, value in outputs.items()
            if not path.exists() or path.read_text() != value
        ]
        if changed:
            raise SystemExit("Formal method contract drift: " + ", ".join(changed))
    else:
        for path, value in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value)


if __name__ == "__main__":
    main()
