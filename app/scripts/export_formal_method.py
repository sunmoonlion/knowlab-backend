"""Export the author-owned definition/compiler to an explicitly named consumer.

No runtime compatibility adapter is generated. Provider source and generated
schema are pinned together so a consumer cannot silently interpret a new shape.
"""

import argparse
import hashlib
import json
from pathlib import Path

from app.domain.knowbots.schema import FORMAL_METHOD, render

HEADER = "# Generated by KnowLab scripts/export_formal_method.py; do not edit.\n"
FILES = {
    "formal_method.py": "formal_method_generated.py",
    "formal_method_compiler.py": "formal_method_compiler_generated.py",
}


def exported(source: str) -> str:
    return HEADER + source.replace(
        "app.domain.knowbots.managed_capabilities_generated",
        "app.domain.workbench.method_capabilities",
    ).replace(
        "app.domain.knowbots.formal_method",
        "app.domain.workbench.formal_method_generated",
    )


def generate(consumer: Path) -> dict[Path, str]:
    provider = Path(__file__).resolve().parents[1] / "app/domain/knowbots"
    sources = {name: (provider / name).read_text() for name in FILES}
    outputs = {
        consumer / "app/domain/workbench" / FILES[name]: exported(content)
        for name, content in sources.items()
    }
    schema = render("definition.schema.json", FORMAL_METHOD)
    outputs[consumer / "contracts/formal-method-v1.json"] = schema
    lock = {
        "provider": "knowlab",
        "contract": "knowlab/formal-method/v1",
        "source_sha256": {
            name: hashlib.sha256(value.encode()).hexdigest()
            for name, value in sources.items()
        },
        "schema_sha256": hashlib.sha256(schema.encode()).hexdigest(),
    }
    outputs[consumer / "contracts/formal-method-lock.json"] = (
        json.dumps(lock, indent=2) + "\n"
    )
    return outputs


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--consumer", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = generate(args.consumer.resolve())
    if args.check:
        changed = [
            str(path)
            for path, value in outputs.items()
            if not path.exists() or path.read_text() != value
        ]
        if changed:
            raise SystemExit("Formal method contract drift: " + ", ".join(changed))
    else:
        for path, value in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value)


if __name__ == "__main__":
    main()
