"""Provider lock and author compilation preserve the runtime's exact requirements."""

import hashlib
import json
from pathlib import Path
from unittest.mock import AsyncMock

import pytest

from app.application.errors.exceptions import BadRequestError, NotFoundError
from app.domain.knowbots.compile import decompile, pack_problems
from app.domain.knowbots.managed_authoring import CODE, MESSAGE
from app.domain.knowbots.managed_capabilities_generated import MethodCapabilities
from tests.knowbot_fakes import OWNER
from tests.test_knowbot_incubation_service import Wired
from tests.test_knowbot_workdraft_compile import body, build

REQ = {
    "tools": [{"url": "https://tools.example.test/mcp", "name": "send"}],
    "skills": [{"name": "notice", "version": "1", "digest": "a" * 64}],
}


def test_authoring_and_import_refuse_technical_only_requirements():
    doc = body()
    doc["steps"][0]["advanced"] = {"managed_capabilities": REQ}
    manifest, problems = build(doc)
    assert any(p.message == MESSAGE for p in problems)
    assert any(p.message == MESSAGE for p in pack_problems(manifest["pack"]))
    assert manifest["pack"]["workflow"][0]["managed_capabilities"] == REQ
    with pytest.raises(ValueError, match="MCP / Skill"):
        decompile(manifest)
    assert "managed_capabilities" not in build()[0]["pack"]["workflow"][0]
    with pytest.raises(ValueError):
        MethodCapabilities.model_validate(
            {"tools": [{"url": "https://user:secret@example.test/mcp", "name": "send"}]}
        )
    with pytest.raises(ValueError):
        MethodCapabilities.model_validate({**REQ, "token": "must-not-be-in-a-pack"})


def test_runtime_provider_lock():
    root = Path(__file__).resolve().parents[1]
    generated = root / "app/domain/knowbots/managed_capabilities_generated.py"
    lock = json.loads(
        (generated.parent / "managed-capabilities-v1.lock.json").read_text()
    )
    assert hashlib.sha256(generated.read_bytes()).hexdigest() == lock["model_sha256"]
    provider = root.parents[2] / "knowbench-app/knowbench-backend/app"
    source = provider / "app/domain/workbench/method_capabilities.py"
    if source.exists():
        expected = (
            "# Generated by knowbench-backend/scripts/export_method_capabilities.py; "
            "do not edit.\n" + source.read_text().split("\ndef matches_tool")[0]
        )
        assert generated.read_text() == expected
        assert (
            hashlib.sha256(
                (provider / "contracts/method-capabilities-v1.json").read_bytes()
            ).hexdigest()
            == lock["schema_sha256"]
        )


async def test_picker_refuses_authoring_without_querying_installed_assets():
    w = Wired()
    request = await w.request()
    w.runtime.capabilities = AsyncMock(return_value={"tools": [], "skills": []})
    with pytest.raises(BadRequestError) as error:
        await w.inc.capabilities(OWNER, str(request.id))
    assert error.value.code == CODE
    with pytest.raises(NotFoundError):
        await w.inc.capabilities("different-author", str(request.id))
    w.runtime.capabilities.assert_not_awaited()


@pytest.mark.parametrize("kind", ["tools", "skills"])
async def test_save_rejects_bindings_and_leaves_existing_draft_unchanged(kind):
    from copy import deepcopy

    from tests.test_knowbot_workdraft_service import CELLS

    w = Wired()
    request = await w.request()
    saved = await w.works.save(OWNER, str(request.id), revision=0, edits=CELLS)
    before = deepcopy(saved.body)
    with pytest.raises(BadRequestError) as error:
        await w.works.save(
            OWNER,
            str(request.id),
            revision=saved.revision,
            edits=[
                ("steps/overview/advanced", {"managed_capabilities": {kind: REQ[kind]}})
            ],
        )
    assert error.value.code == CODE
    _, current = await w.works.get(OWNER, str(request.id))
    assert current.body == before and current.revision == saved.revision
    edited = await w.works.save(
        OWNER,
        str(request.id),
        revision=saved.revision,
        edits=[("steps/overview/advanced", {"managed_capabilities": None})],
    )
    assert edited.revision == saved.revision + 1


async def test_import_and_publish_cannot_bypass_the_authoring_gate():
    from copy import deepcopy

    from tests.test_knowbot_workdraft_service import CELLS

    w = Wired()
    request = await w.request()
    saved = await w.works.save(OWNER, str(request.id), revision=0, edits=CELLS)
    doc = body()
    doc["steps"][0]["advanced"] = {"managed_capabilities": REQ}
    manifest, _ = build(doc)
    with pytest.raises(BadRequestError, match="MCP / Skill"):
        await w.works.import_manifest(
            OWNER, str(request.id), revision=saved.revision, manifest=manifest
        )
    contaminated = deepcopy(saved.body)
    contaminated["steps"][0]["advanced"]["managed_capabilities"] = REQ
    await w.repo.update_workdraft(
        saved.id, body=contaminated, sources=saved.sources, revision=saved.revision
    )
    with pytest.raises(BadRequestError, match="MCP / Skill"):
        await w.works.publish(OWNER, str(request.id))
    assert not w.repo.drafts


@pytest.mark.parametrize("location", ["fixed", "dynamic", "reference"])
def test_pack_gate_checks_direct_and_referenced_implementations(location):
    from app.domain.knowbots.managed_authoring import pack_paths

    if location == "fixed":
        pack = {"workflow": [{"managed_capabilities": REQ}]}
    elif location == "dynamic":
        pack = {"method_units": [{"contract": {"managed_capabilities": REQ}}]}
    else:
        pack = {
            "method_sources": {
                "unit": {
                    "definition": {"step": {"advanced": {"managed_capabilities": REQ}}}
                }
            }
        }
    assert len(pack_paths(pack)) == 1
    assert pack_problems(pack)[0].message == MESSAGE
